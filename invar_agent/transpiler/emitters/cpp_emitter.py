"""Lower UAST to C++ (Clang++/G++ -O3 -std=c++20 -fPIC -shared).

Supported ``v9_transpiler_friendly`` subset:

- top-level pure functions; a parameter named ``buf`` is the
  ``SimulationBuffer*``, every other parameter is a ``double``;
- locals typed by inference: ``int`` (index arithmetic), ``double``,
  ``list[float]`` (``[0.0] * n`` / ``[a, b]``) and ``list[list[float]]``
  (``[[0.0] * n for _ in range(m)]``);
- ``for`` over ``range(stop)`` / ``range(start, stop[, step])``; ``while``
  loops always receive an injected iteration guard;
- ``math.*`` functions, ``abs/min/max/int/float/len``, user functions and
  the deterministic intrinsics ``prng_uniform(seed, k)``, ``clamp`` and
  ``sign``. Any other call is rejected at emit time, so generated kernels
  can never reach libc I/O, the network or the filesystem.

Every function named ``simulation_step*`` or ``layer_*`` with the
signature ``(buf, dt)`` is exported as a C-ABI entry point
``extern "C" void <entry>(SimulationBuffer*)``; ``simulation_step`` is
exported as ``execute_step``.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Set

from .base import EmitterError, render_literal

WHILE_GUARD = 10_000_000

_MATH_FUNCS = {
    "sqrt", "sin", "cos", "tan", "asin", "acos", "atan", "atan2", "sinh", "cosh",
    "tanh", "exp", "log", "log10", "log2", "log1p", "expm1", "ceil", "floor",
    "pow", "fabs", "fmod", "hypot", "copysign", "trunc", "isfinite", "isnan",
    "isinf", "radians", "degrees",
}
_INTRINSICS = {"prng_uniform": 2, "clamp": 3, "clip": 3, "sign": 1, "sgn": 1,
               "sq": 1, "lerp": 3, "safe_div": 2}
_CMPS = {"==": "==", "!=": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">=",
         "is": "==", "is_not": "!="}

_PRELUDE = """// Generated by invar-agent transpiler (CppEmitter)
#include <cstdint>
#include <cmath>
#include <vector>
#include <tuple>

extern "C" {
typedef struct SimulationBuffer {
    size_t size;
    double dt;
    uint32_t steps;
    double* data;
} SimulationBuffer;
}

namespace invar {
static inline long pymod_i(long a, long b) { long r = a % b; return (r != 0 && ((r < 0) != (b < 0))) ? r + b : r; }
static inline long floordiv_i(long a, long b) { long q = a / b; return ((a % b != 0) && ((a < 0) != (b < 0))) ? q - 1 : q; }
static inline double pymod_f(double a, double b) { double r = std::fmod(a, b); return (r != 0.0 && ((r < 0.0) != (b < 0.0))) ? r + b : r; }
static inline double clamp(double x, double lo, double hi) { return x < lo ? lo : (x > hi ? hi : x); }
static inline double clip(double x, double lo, double hi) { return clamp(x, lo, hi); }
static inline double sign(double x) { return (x > 0.0) - (x < 0.0); }
static inline double sgn(double x) { return sign(x); }
static inline double sq(double x) { return x * x; }
static inline double lerp(double a, double b, double t) { return a + t * (b - a); }
static inline double safe_div(double a, double b) { return a / (std::fabs(b) > 1e-30 ? b : 1e-30); }
static inline double prng_uniform(double seed, double k) {
    uint64_t z = static_cast<uint64_t>(static_cast<int64_t>(seed)) * 0x9E3779B97F4A7C15ULL
               + static_cast<uint64_t>(static_cast<int64_t>(k)) + 0x9E3779B97F4A7C15ULL;
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
    z = z ^ (z >> 31);
    return static_cast<double>(z >> 11) * (1.0 / 9007199254740992.0);
}
}  // namespace invar
"""

INT, FLOAT, VEC, VEC2, BUF, BOOL = "int", "double", "vec", "vec2", "buf", "bool"


def _ref_name(node: Optional[Dict[str, Any]]) -> Optional[str]:
    if isinstance(node, dict) and node.get("type") == "reference":
        return node.get("name")
    return None


def _call_name(node: Dict[str, Any]) -> Optional[str]:
    fn = node.get("function") or {}
    return fn.get("name") if fn.get("type") == "reference" else None


def _call_args(node: Dict[str, Any]) -> List[Dict[str, Any]]:
    args = node.get("arguments") or []
    if not args and node.get("argument") is not None:
        args = [node["argument"]]
    return args


def is_entry_function(fn: Dict[str, Any]) -> bool:
    name = str(fn.get("name", ""))
    params = fn.get("params") or []
    return (name.startswith("simulation_step") or name.startswith("layer_")) \
        and len(params) >= 1 and params[0] == "buf"


def entry_symbol(name: str) -> str:
    return "execute_step" if name == "simulation_step" else f"execute_{name}"


class CppEmitter:
    """Emits a self-contained C++20 simulation kernel with C-ABI entry points."""

    def __init__(self, buffer_struct: str = "SimulationBuffer"):
        self.buffer_struct = buffer_struct
        self.functions: Dict[str, Dict[str, Any]] = {}
        self.returns: Dict[str, str] = {}
        self.globals: Dict[str, str] = {}
        self.types: Dict[str, str] = {}
        # Simple names bound to ``buf.data`` (e.g. ``state = buf.data``) are
        # pointer aliases, never scalar locals.
        self._aliases: Dict[str, str] = {}

    # -- type inference --------------------------------------------------
    def _type_of(self, node: Optional[Dict[str, Any]]) -> str:
        if node is None:
            return FLOAT
        t = node.get("type")
        if t == "literal":
            v = node.get("value")
            if isinstance(v, bool):
                return BOOL
            return INT if isinstance(v, int) else FLOAT
        if t == "reference":
            name = node.get("name", "")
            if name == "buf.size" or name == "buf.steps":
                return INT
            if name == "buf.dt":
                return FLOAT
            return self.types.get(name, self.globals.get(name, FLOAT))
        if t == "attribute":
            return INT if node.get("attr") in ("size", "steps") else FLOAT
        if t == "binop":
            op = node.get("op")
            lt, rt = self._type_of(node.get("left")), self._type_of(node.get("right"))
            if op == "*" and (node.get("left") or {}).get("type") == "list":
                return VEC
            if op == "/" or op == "**":
                return FLOAT
            if lt in (INT, BOOL) and rt in (INT, BOOL):
                return INT
            return FLOAT
        if t == "unaryop":
            if node.get("op") == "not":
                return BOOL
            return self._type_of(node.get("operand"))
        if t in ("compare", "set_member"):
            return BOOL
        if t in ("call", "user_function_call"):
            name = _call_name(node) or ""
            args = _call_args(node)
            if name.startswith("__boolop_"):
                return BOOL
            if name in ("len", "int"):
                return INT
            if name in ("abs", "min", "max") and args and all(
                    self._type_of(a) == INT for a in args):
                return INT
            if name in self.returns:
                return self.returns[name]
            return FLOAT
        if t == "subscript":
            vt = self._type_of(node.get("value"))
            return VEC if vt == VEC2 else FLOAT
        if t == "list":
            elems = node.get("elements") or []
            return VEC2 if elems and (elems[0] or {}).get("type") == "list" else VEC
        if t == "list2d_alloc":
            return VEC2
        if t == "if":
            then = node.get("then") or [None]
            other = node.get("else") or [None]
            a, b = self._type_of(then[-1]), self._type_of(other[-1])
            return INT if a == INT and b == INT else FLOAT
        return FLOAT

    def _is_buf_data_ref(self, node: Optional[Dict[str, Any]]) -> bool:
        """True for ``buf.data`` / ``buf->data``-style value references."""
        if isinstance(node, dict) and node.get("type") == "reference":
            return node.get("name") == "buf.data"
        if isinstance(node, dict) and node.get("type") == "attribute":
            return _ref_name(node.get("value")) == "buf" and node.get("attr") == "data"
        return False

    def _collect_locals(self, fn: Dict[str, Any]) -> Dict[str, str]:
        """Fixed-point type inference over every local bound in the function."""
        params = fn.get("params") or []
        self.types = {p: (BUF if p == "buf" else FLOAT) for p in params}
        self._aliases = {}
        loop_vars: Set[str] = set()
        assigns: List[tuple] = []

        def walk(stmts):
            for s in stmts or []:
                if not isinstance(s, dict):
                    continue
                t = s.get("type")
                if t == "binding" and isinstance(s.get("name"), str) and s.get("target") is None:
                    if self._is_buf_data_ref(s.get("value")):
                        self._aliases[s["name"]] = "buf->data"
                    else:
                        assigns.append((s["name"], s.get("value")))
                elif t == "multi_binding":
                    for n, v in zip(s.get("names") or [], s.get("values") or []):
                        assigns.append((n, v))
                elif t == "tuple_unbind":
                    for n in (s.get("names") or []):
                        assigns.append((n, {"type": "literal", "value": 0.0}))
                elif t == "loop_for":
                    var = _ref_name(s.get("target"))
                    if var:
                        loop_vars.add(var)
                    walk(s.get("body"))
                elif t == "loop_while":
                    walk(s.get("body"))
                elif t == "if":
                    walk(s.get("then"))
                    walk(s.get("else"))

        walk(fn.get("body"))
        for v in loop_vars:
            self.types.setdefault(v, INT)
        local_types: Dict[str, str] = {}
        for _ in range(4):
            changed = False
            for name, value in assigns:
                if name in params or name in loop_vars:
                    continue
                vt = self._type_of(value)
                if vt == BOOL:
                    vt = INT
                prev = local_types.get(name)
                new = vt if prev is None else (prev if prev == vt else
                                               (FLOAT if {prev, vt} <= {INT, FLOAT} else prev))
                if new != prev:
                    local_types[name] = new
                    self.types[name] = new
                    changed = True
            if not changed:
                break
        return local_types

    # -- expressions -----------------------------------------------------
    def _num(self, node) -> str:
        """Emit an expression coerced to double."""
        e = self.emit_expr(node)
        return e if self._type_of(node) == FLOAT else f"static_cast<double>({e})"

    def emit_expr(self, node: Optional[Dict[str, Any]]) -> str:
        if node is None:
            raise EmitterError("missing expression")
        t = node.get("type")
        if t == "literal":
            v = node.get("value")
            if isinstance(v, str) or v is None:
                raise EmitterError(f"unsupported literal {v!r} in kernel")
            return render_literal(v, "cpp")
        if t == "reference":
            name = str(node.get("name", ""))
            if name in self._aliases:
                return self._aliases[name]
            if name.startswith("buf."):
                attr = name.split(".", 1)[1]
                if attr not in ("data", "size", "dt", "steps"):
                    raise EmitterError(f"unsupported buffer attribute buf.{attr}")
                return f"buf->{attr}" if attr != "size" else "static_cast<long>(buf->size)"
            if "." in name:
                raise EmitterError(f"unsupported attribute reference {name!r}")
            return name
        if t == "attribute":
            value = node.get("value") or {}
            if _ref_name(value) == "buf" and node.get("attr") in ("data", "dt", "steps"):
                return f"buf->{node.get('attr')}"
            if _ref_name(value) == "buf" and node.get("attr") == "size":
                return "static_cast<long>(buf->size)"
            raise EmitterError(f"unsupported attribute access .{node.get('attr')}")
        if t == "binop":
            return self._emit_binop(node)
        if t == "unaryop":
            op = node.get("op")
            operand = self.emit_expr(node.get("operand"))
            if op == "-":
                return f"(-{operand})"
            if op == "+":
                return operand
            if op == "not":
                return f"(!{operand})"
            raise EmitterError(f"unsupported unaryop {op!r}")
        if t in ("call", "user_function_call"):
            return self._emit_call(node)
        if t == "compare":
            op = node.get("op", "==")
            sym = _CMPS.get(op)
            if sym is None:
                raise EmitterError(f"unsupported comparison {op!r}")
            return f"({self.emit_expr(node.get('left'))} {sym} {self.emit_expr(node.get('right'))})"
        if t == "if":
            cond = self.emit_expr(node.get("condition"))
            then = (node.get("then") or [None])[-1]
            other = (node.get("else") or [None])[-1]
            return f"({cond} ? {self._num(then)} : {self._num(other)})"
        if t == "subscript":
            value = node.get("value")
            slice_node = node.get("slice")
            # ``buf[i]`` is shorthand for ``buf.data[i]`` inside kernels.
            if isinstance(value, dict) and value.get("type") == "reference" \
                    and value.get("name") == "buf":
                base = "buf->data"
            else:
                base = self.emit_expr(value)
            # Python negative indexing (x[-k] == x[size - k]) is UB in C++;
            # lower it to a bounds-safe size-relative calculation.
            if (isinstance(slice_node, dict) and slice_node.get("type") == "unaryop"
                    and slice_node.get("op") == "-"
                    and self._type_of(slice_node.get("operand")) == INT):
                operand = self.emit_expr(slice_node.get("operand"))
                return (f"{base}[static_cast<long>({base}.size()) - ({operand})]")
            idx = self.emit_expr(slice_node)
            if self._type_of(slice_node) != INT:
                idx = f"static_cast<long>({idx})"
            if isinstance(value, dict) and value.get("type") == "reference" \
                    and str(value.get("name", "")).startswith("__tuple"):
                return f"std::get<{idx}>({base})"
            return f"{base}[{idx}]"
        if t == "tuple":
            return f"std::tuple<{', '.join('double' for _ in (node.get('elements') or []))}>"
        if t == "list":
            elems = node.get("elements") or []
            if elems and (elems[0] or {}).get("type") == "list":
                rows = ", ".join(self.emit_expr(e) for e in elems)
                return f"std::vector<std::vector<double>>{{{rows}}}"
            return "std::vector<double>{" + ", ".join(self._num(e) for e in elems) + "}"
        if t == "list2d_alloc":
            rows = self.emit_expr(node.get("rows"))
            cols = self.emit_expr(node.get("cols"))
            fill = self._num(node.get("fill"))
            return (f"std::vector<std::vector<double>>(static_cast<size_t>({rows}), "
                    f"std::vector<double>(static_cast<size_t>({cols}), {fill}))")
        raise EmitterError(f"unsupported expression type {t!r}")

    def _emit_binop(self, node: Dict[str, Any]) -> str:
        op = node.get("op")
        left, right = node.get("left"), node.get("right")
        if op == "*" and (left or {}).get("type") == "list":
            elems = left.get("elements") or []
            if len(elems) != 1:
                raise EmitterError("list repetition must be [value] * n")
            return (f"std::vector<double>(static_cast<size_t>({self.emit_expr(right)}), "
                    f"{self._num(elems[0])})")
        lt, rt = self._type_of(left), self._type_of(right)
        both_int = lt in (INT, BOOL) and rt in (INT, BOOL)
        if op == "**":
            return f"std::pow({self._num(left)}, {self._num(right)})"
        if op == "/":
            return f"({self._num(left)} / {self._num(right)})"
        if op == "//":
            if both_int:
                return f"invar::floordiv_i({self.emit_expr(left)}, {self.emit_expr(right)})"
            return f"std::floor({self._num(left)} / {self._num(right)})"
        if op == "%":
            if both_int:
                return f"invar::pymod_i({self.emit_expr(left)}, {self.emit_expr(right)})"
            return f"invar::pymod_f({self._num(left)}, {self._num(right)})"
        if op in ("+", "-", "*"):
            return f"({self.emit_expr(left)} {op} {self.emit_expr(right)})"
        if op in ("&", "|", "^", "<<", ">>") and both_int:
            return f"({self.emit_expr(left)} {op} {self.emit_expr(right)})"
        raise EmitterError(f"unsupported binop {op!r}")

    def _emit_call(self, node: Dict[str, Any]) -> str:
        name = _call_name(node)
        args = _call_args(node)
        if name and name.startswith("__boolop_"):
            vals = args[0].get("value", []) if args and args[0].get("type") == "literal" else []
            op = "&&" if "and" in name else "||"
            return "(" + f" {op} ".join(self.emit_expr(v) for v in vals) + ")"
        if name is None:
            raise EmitterError("only direct function calls are supported")
        if name == "len" and len(args) == 1:
            target = args[0]
            if _ref_name(target) == "buf.data" or (
                    target.get("type") == "attribute" and target.get("attr") == "data"):
                return "static_cast<long>(buf->size)"
            if self._type_of(target) in (VEC, VEC2):
                return f"static_cast<long>({self.emit_expr(target)}.size())"
            raise EmitterError("len() is only supported on buf.data and local lists")
        if name == "abs" and len(args) == 1:
            if self._type_of(args[0]) == INT:
                return f"std::labs({self.emit_expr(args[0])})"
            return f"std::fabs({self._num(args[0])})"
        if name in ("min", "max") and len(args) >= 2:
            if all(self._type_of(a) == INT for a in args):
                fn = "std::min<long>" if name == "min" else "std::max<long>"
                expr = self.emit_expr(args[0])
                for a in args[1:]:
                    expr = f"({expr} {'<' if name == 'min' else '>'} {self.emit_expr(a)} ? {expr} : {self.emit_expr(a)})"
                return expr
            fn = "std::fmin" if name == "min" else "std::fmax"
            expr = self._num(args[0])
            for a in args[1:]:
                expr = f"{fn}({expr}, {self._num(a)})"
            return expr
        if name == "int" and len(args) == 1:
            return f"static_cast<long>({self.emit_expr(args[0])})"
        if name == "float" and len(args) == 1:
            return self._num(args[0])
        if name in ("math.radians", "math.degrees"):
            if len(args) != 1:
                raise EmitterError(f"{name}() expects 1 argument")
            x = self._num(args[0])
            if name == "math.radians":
                return f"(({x}) * 3.14159265358979323846 / 180.0)"
            return f"(({x}) * 180.0 / 3.14159265358979323846)"
        if name.startswith("math."):
            fn = name.split(".", 1)[1]
            if fn not in _MATH_FUNCS:
                raise EmitterError(f"unsupported math function math.{fn}")
            return f"std::{fn}(" + ", ".join(self._num(a) for a in args) + ")"
        if name in _INTRINSICS:
            if len(args) != _INTRINSICS[name]:
                raise EmitterError(f"{name}() expects {_INTRINSICS[name]} arguments")
            return f"invar::{name}(" + ", ".join(self._num(a) for a in args) + ")"
        if name in self.functions:
            params = self.functions[name].get("params") or []
            if len(params) != len(args):
                raise EmitterError(f"{name}() expects {len(params)} arguments, got {len(args)}")
            rendered = []
            for p, a in zip(params, args):
                if p == "buf":
                    if _ref_name(a) != "buf":
                        raise EmitterError(f"{name}(): the buf parameter must receive buf")
                    rendered.append("buf")
                else:
                    rendered.append(self._num(a))
            return f"{name}(" + ", ".join(rendered) + ")"
        raise EmitterError(f"call to {name!r} is not allowed in sandbox kernels")

    # -- statements ------------------------------------------------------
    def emit_stmt(self, node: Dict[str, Any], indent: int = 1) -> str:
        pad = "    " * indent
        t = node.get("type")
        if t == "binding":
            target = node.get("target")
            value = node.get("value")
            if target is not None:
                return f"{pad}{self.emit_expr(target)} = {self._num(value)};\n"
            name = node.get("name")
            if not isinstance(name, str):
                raise EmitterError("unsupported binding target")
            if name in self._aliases:
                # ``state = buf.data`` is a no-op: the alias is bound at the
                # top of the function and always points at the live buffer.
                return ""
            ty = self.types.get(name, FLOAT)
            if ty in (VEC, VEC2, INT, BOOL):
                rendered = self.emit_expr(value)
            else:
                rendered = self._num(value)
            return f"{pad}{name} = {rendered};\n"
        if t == "multi_binding":
            names = node.get("names") or []
            values = node.get("values") or []
            out = [pad + "{\n"]
            for i, (n, v) in enumerate(zip(names, values)):
                ty = self.types.get(n, FLOAT)
                cty = {INT: "long", VEC: "std::vector<double>",
                       VEC2: "std::vector<std::vector<double>>"}.get(ty, "double")
                rendered = self._num(v) if ty == FLOAT else self.emit_expr(v)
                out.append(f"{pad}    {cty} __tmp{i} = {rendered};\n")
            for i, n in enumerate(names):
                out.append(f"{pad}    {n} = __tmp{i};\n")
            out.append(pad + "}\n")
            return "".join(out)
        if t == "return":
            value = node.get("value")
            if value is None:
                return f"{pad}return;\n"
            if value.get("type") == "tuple":
                elems = value.get("elements") or []
                rendered = ", ".join(self._num(e) for e in elems)
                return f"{pad}return std::make_tuple({rendered});\n"
            ret = self.returns.get(self._current_fn, FLOAT)
            rendered = self._num(value) if ret == FLOAT else self.emit_expr(value)
            return f"{pad}return {rendered};\n"
        if t == "tuple_unbind":
            # x, y, z = fn(...) where fn returns std::tuple<double, ...>
            names = node.get("names") or []
            call = self.emit_expr(node.get("value"))
            assigns = "".join(
                f"{pad}    {n} = std::get<{i}>(__tuple_tmp);\n"
                for i, n in enumerate(names))
            return (f"{pad}{{\n{pad}    auto __tuple_tmp = {call};\n{assigns}{pad}}}\n")
        if t == "loop_for":
            return self._emit_for(node, indent)
        if t == "loop_while":
            cond = self.emit_expr(node.get("condition"))
            body = self._emit_body(node.get("body"), indent + 1)
            guard = f"__guard_{indent}"
            return (f"{pad}{{ long {guard} = 0;\n"
                    f"{pad}while (({cond}) && {guard}++ < {WHILE_GUARD}L) {{\n{body}{pad}}} }}\n")
        if t == "if":
            cond = self.emit_expr(node.get("condition"))
            then_body = self._emit_body(node.get("then"), indent + 1)
            else_body = self._emit_body(node.get("else"), indent + 1)
            else_part = f" else {{\n{else_body}{pad}}}" if else_body else ""
            return f"{pad}if ({cond}) {{\n{then_body}{pad}}}{else_part}\n"
        if t == "expr":
            return f"{pad}{self.emit_expr(node.get('value'))};\n"
        if t == "pass":
            return ""
        if t == "break":
            return f"{pad}break;\n"
        if t == "continue":
            return f"{pad}continue;\n"
        if t == "function_declaration":
            raise EmitterError("nested functions are not supported")
        raise EmitterError(f"unsupported statement type {t!r}")

    def _emit_body(self, stmts, indent: int) -> str:
        return "".join(self.emit_stmt(s, indent) for s in (stmts or []) if s)

    def _emit_for(self, node: Dict[str, Any], indent: int) -> str:
        pad = "    " * indent
        var = _ref_name(node.get("target"))
        if not var:
            raise EmitterError("for-loop target must be a simple name")
        it = node.get("iter") or {}
        if it.get("type") not in ("call",) or _call_name(it) != "range":
            raise EmitterError("for loops must iterate over range(...)")
        args = _call_args(it)
        if not 1 <= len(args) <= 3:
            raise EmitterError("range() takes 1-3 arguments")
        as_long = lambda a: f"static_cast<long>({self.emit_expr(a)})"  # noqa: E731
        start = as_long(args[0]) if len(args) >= 2 else "0L"
        stop = as_long(args[1] if len(args) >= 2 else args[0])
        step_node = args[2] if len(args) == 3 else None
        body = self._emit_body(node.get("body"), indent + 1)
        if step_node is None:
            return (f"{pad}for (long {var} = {start}; {var} < {stop}; ++{var}) {{\n"
                    f"{body}{pad}}}\n")
        step = as_long(step_node)
        neg = step_node.get("type") == "unaryop" and step_node.get("op") == "-"
        lit = step_node.get("value") if step_node.get("type") == "literal" else None
        if isinstance(lit, int) and lit == 0:
            raise EmitterError("range() step must not be zero")
        if neg or (isinstance(lit, int) and lit < 0):
            cond = f"{var} > {stop}"
        elif isinstance(lit, int):
            cond = f"{var} < {stop}"
        else:
            cond = f"(({step}) > 0 ? {var} < {stop} : {var} > {stop})"
        return (f"{pad}for (long {var} = {start}; {cond}; {var} += {step}) {{\n"
                f"{body}{pad}}}\n")

    def _cret(self, ret: str) -> str:
        if ret.startswith("__tuple"):
            arity = int(ret[len("__tuple"):])
            return "std::tuple<" + ", ".join(["double"] * arity) + ">"
        return {"void": "void", INT: "long", FLOAT: "double"}[ret]

    # -- functions -------------------------------------------------------
    def _return_type(self, fn: Dict[str, Any]) -> str:
        rets: List[Dict[str, Any]] = []

        def walk(stmts):
            for s in stmts or []:
                if not isinstance(s, dict):
                    continue
                if s.get("type") == "return" and s.get("value") is not None:
                    rets.append(s["value"])
                for key in ("body", "then", "else"):
                    if isinstance(s.get(key), list):
                        walk(s[key])

        walk(fn.get("body"))
        if not rets:
            return "void"
        self._collect_locals(fn)
        if any(r.get("type") == "tuple" for r in rets):
            # Multi-value return: std::tuple<double, ...> with one double per element.
            arity = 0
            for r in rets:
                if r.get("type") == "tuple":
                    arity = max(arity, len(r.get("elements") or []))
            return f"__tuple{arity}"
        types = {self._type_of(r) for r in rets}
        return INT if types <= {INT, BOOL} else FLOAT

    def _emit_function(self, fn: Dict[str, Any]) -> str:
        name = fn.get("name", "fn")
        self._current_fn = name
        params = fn.get("params") or []
        local_types = self._collect_locals(fn)
        ret = self.returns.get(name, "void")
        cret = self._cret(ret)
        plist = ", ".join(f"{self.buffer_struct}* buf" if p == "buf" else f"double {p}"
                          for p in params)
        lines = [f"static {cret} {name}({plist}) {{"]
        for local, ty in sorted(local_types.items()):
            cty = {INT: "long", VEC: "std::vector<double>",
                   VEC2: "std::vector<std::vector<double>>"}.get(ty, "double")
            init = "{}" if ty in (VEC, VEC2) else ("0" if ty == INT else "0.0")
            lines.append(f"    {cty} {local} = {init}; (void){local};")
        # ``state[i]`` alias: kernels may index the trajectory through a bare
        # ``state`` name (``state = buf.data`` or direct use). Bind it to the
        # live buffer unless the function declares its own scalar ``state``.
        if "buf" in params and "state" not in local_types and "state" not in params:
            lines.append("    double* state = buf->data; (void)state;")
        body = self._emit_body(fn.get("body"), 1)
        lines.append(body.rstrip("\n") if body.strip() else "")
        if ret != "void" and not any(
                isinstance(s, dict) and s.get("type") == "return" and s.get("value") is not None
                for s in (fn.get("body") or [])):
            lines.append("    return {};" if str(ret).startswith("__tuple") else "    return 0;")
        lines.append("}")
        return "\n".join(l for l in lines if l != "") + "\n"

    # -- whole module ----------------------------------------------------
    def emit_module(self, uast: Dict[str, Any]) -> str:
        children = [c for c in (uast.get("children") or []) if isinstance(c, dict)]
        funcs = [c for c in children if c.get("type") == "function_declaration"]
        self.functions = {f["name"]: f for f in funcs}
        self.globals = {}
        self.returns = {}
        out = [_PRELUDE]
        for g in children:
            if g.get("type") == "binding" and isinstance(g.get("name"), str) \
                    and g.get("target") is None:
                self.types = {}
                ty = self._type_of(g.get("value"))
                if ty not in (INT, FLOAT, BOOL):
                    raise EmitterError("module-level constants must be scalars")
                cty = "long" if ty in (INT, BOOL) else "double"
                val = self.emit_expr(g.get("value"))
                out.append(f"static const {cty} {g['name']} = {val};")
                self.globals[g["name"]] = INT if ty in (INT, BOOL) else FLOAT
            elif g.get("type") not in ("function_declaration", "expr"):
                raise EmitterError(f"unsupported top-level statement {g.get('type')!r}")
        # Return types first (two passes so callers see callee types).
        for _ in range(2):
            for f in funcs:
                self.returns[f["name"]] = self._return_type(f)
        for f in funcs:
            plist = ", ".join(f"{self.buffer_struct}* buf" if p == "buf" else "double"
                              for p in (f.get("params") or []))
            out.append(f"static {self._cret(self.returns[f['name']])} {f['name']}({plist});")
        out.append("")
        for f in funcs:
            out.append(self._emit_function(f))
        entries = [f for f in funcs if is_entry_function(f)]
        if not any(f["name"] == "simulation_step" for f in entries):
            raise EmitterError("module must define simulation_step(buf, dt)")
        for f in entries:
            params = f.get("params") or []
            call_args = ["buf"] + ["buf->dt" if p == "dt" else "0.0" for p in params[1:]]
            out.append(f'extern "C" void {entry_symbol(f["name"])}({self.buffer_struct}* buf) {{')
            out.append(f"    {f['name']}({', '.join(call_args)});")
            out.append("    buf->steps += 1;")
            out.append("}")
        return "\n".join(out) + "\n"

    def entry_points(self, uast: Dict[str, Any]) -> List[str]:
        """Names of the exported (buf, dt) entry functions in a module UAST."""
        return [c["name"] for c in (uast.get("children") or [])
                if isinstance(c, dict) and c.get("type") == "function_declaration"
                and is_entry_function(c)]
