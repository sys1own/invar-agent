"""Lower UAST to Rust source (materialization target; compilation optional)."""

from __future__ import annotations

from typing import Any, Dict, Optional

from .base import EmitterError, qual_name, render_literal

_INTRINSIC_HELPERS = {
    "clamp": "fn clamp(x: f64, lo: f64, hi: f64) -> f64 { if x < lo { lo } else if x > hi { hi } else { x } }",
    "clip": "fn clip(x: f64, lo: f64, hi: f64) -> f64 { clamp(x, lo, hi) }",
    "sign": "fn sign(x: f64) -> f64 { if x > 0.0 { 1.0 } else if x < 0.0 { -1.0 } else { 0.0 } }",
    "sgn": "fn sgn(x: f64) -> f64 { sign(x) }",
    "sq": "fn sq(x: f64) -> f64 { x * x }",
    "lerp": "fn lerp(a: f64, b: f64, t: f64) -> f64 { a + t * (b - a) }",
    "safe_div": "fn safe_div(a: f64, b: f64) -> f64 { a / if b.abs() > 1e-30 { b } else { 1e-30 } }",
}


def _walk_nodes(node):
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from _walk_nodes(value)
    elif isinstance(node, (list, tuple)):
        for value in node:
            yield from _walk_nodes(value)


def _call_names(uast):
    names = set()
    for node in _walk_nodes(uast):
        if node.get("type") in ("call", "user_function_call"):
            fn = node.get("function") or {}
            if fn.get("type") == "reference" and fn.get("name"):
                names.add(str(fn["name"]))
    return names


class RustEmitter:
    def emit_expr(self, node: Optional[Dict[str, Any]]) -> str:
        if node is None:
            return "()"
        t = node.get("type")
        if t == "literal":
            return render_literal(node.get("value"), "rust")
        if t == "reference":
            return qual_name(str(node.get("name", "")), "rust")
        if t == "binop":
            op = node.get("op", "?")
            left = self.emit_expr(node.get("left"))
            right = self.emit_expr(node.get("right"))
            sym = {"+": "+", "-": "-", "*": "*", "/": "/", "%": "%"}.get(op)
            if sym is None:
                raise EmitterError(f"unsupported rust binop {op!r}")
            return f"({left} {sym} {right})"
        if t == "unaryop":
            op = node.get("op", "?")
            operand = self.emit_expr(node.get("operand"))
            if op == "-":
                return f"(-{operand})"
            if op == "not":
                return f"(!{operand})"
            raise EmitterError(f"unsupported rust unaryop {op!r}")
        if t == "call":
            fn = node.get("function") or {}
            args = node.get("arguments") or []
            if not args and node.get("argument") is not None:
                args = [node["argument"]]
            name = fn.get("name") if fn.get("type") == "reference" else None
            target = qual_name(str(name or ""), "rust") if name else self.emit_expr(fn)
            rendered = ", ".join(self.emit_expr(a) for a in args)
            return f"{target}({rendered})"
        if t == "compare":
            return (f"({self.emit_expr(node.get('left'))} {node.get('op', '==')} "
                    f"{self.emit_expr(node.get('right'))})")
        if t == "subscript":
            return f"{self.emit_expr(node.get('value'))}[{self.emit_expr(node.get('slice'))}]"
        if t == "list":
            elems = node.get("elements") or []
            return "vec![" + ", ".join(self.emit_expr(e) for e in elems) + "]"
        if t == "attribute":
            return f"{self.emit_expr(node.get('value'))}.{node.get('attr')}"
        raise EmitterError(f"unsupported rust expression {t!r}")

    def emit_module(self, uast: Dict[str, Any]) -> str:
        lines = ["// Generated by invar-agent transpiler (RustEmitter)", ""]
        fn_names = {str(child.get("name")) for child in (uast.get("children") or [])
                    if isinstance(child, dict) and child.get("type") == "function_declaration"}
        used = _call_names(uast) - fn_names
        for name in sorted(used & set(_INTRINSIC_HELPERS)):
            lines.append(_INTRINSIC_HELPERS[name])
        if lines[-1] != "":
            lines.append("")
        for child in uast.get("children") or []:
            if not isinstance(child, dict):
                continue
            t = child.get("type")
            if t == "function_declaration":
                params = ", ".join(f"{p}: f64" for p in (child.get("params") or []))
                body = "\n".join(f"    {self.emit_stmt(s)}" for s in (child.get("body") or []) if s)
                lines.append(f"pub fn {child.get('name')}({params}) -> f64 {{")
                lines.append(body or "    0.0")
                lines.append("}")
                lines.append("")
        return "\n".join(lines)

    def emit_stmt(self, node: Dict[str, Any]) -> str:
        t = node.get("type")
        if t == "binding":
            return f"let {node.get('name')} = {self.emit_expr(node.get('value'))};"
        if t == "multi_binding":
            # Tuple unpacking / simultaneous assignment via temporaries so
            # swaps like `a, b = b, a` stay correct.
            names = node.get("names") or []
            values = node.get("values") or []
            tmps = [f"__tmp{i}" for i in range(len(names))]
            lines = [f"let {tmp} = {self.emit_expr(v)};"
                     for tmp, v in zip(tmps, values)]
            lines += [f"let {n} = {tmp};" for n, tmp in zip(names, tmps)]
            return " ".join(lines)
        if t == "return":
            val = node.get("value", node)
            return f"return {self.emit_expr(val)};"
        if t == "loop_for":
            body = "\n".join(f"        {self.emit_stmt(s)}" for s in (node.get("body") or []) if s)
            return f"for _ in 0..{self.emit_expr(node.get('iter'))} {{\n{body}\n    }}"
        if t == "if":
            cond = self.emit_expr(node.get("condition"))
            then = "\n".join(f"        {self.emit_stmt(s)}" for s in (node.get("then") or []) if s)
            other = "\n".join(f"        {self.emit_stmt(s)}" for s in (node.get("else") or []) if s)
            else_part = f" else {{\n{other}\n    }}" if other else ""
            return f"if {cond} {{\n{then}\n    }}{else_part}"
        raise EmitterError(f"unsupported rust statement {t!r}")
